-- 排他制御（楽観ロック）用の版数カラムを追加する。
--
-- 【防ぎたい事故】
--   10:00 Aさんが社員E0001の編集画面を開く（部署=営業部）
--   10:01 Bさんが同じ社員の編集画面を開く
--   10:02 Bさんが部署を「開発部」にして保存
--   10:03 Aさんが備考だけ直して保存
--   → Aさんの画面は10:00時点の「営業部」を持っているので、Bさんの変更が消える。
--     しかも誰も気づかない。
--
-- version を持たせておくと、更新時に「読んだときの版数」と「今の版数」を突き合わせられる。
-- 食い違っていれば、後から保存した人にエラーを出して上書きを止められる。
--
-- 既存の行には 0 を入れる（default 0）。以後、更新のたびに Hibernate が +1 する。

alter table employee add column version bigint not null default 0;
